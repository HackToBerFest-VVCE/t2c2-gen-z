import type { AgentOutput } from '../types';
import type { LocalModelProvider, AgentExecutionTraceStep } from './types';
import { deterministicAgent } from './deterministic';

export class OllamaModelProvider implements LocalModelProvider {
  id = 'ollama';
  name = 'Ollama Local LLM';
  description = 'On-device open-source LLM (e.g. Llama 3.2, Phi 3, TinyLlama) running through local Ollama API.';
  endpoint = 'http://localhost:11434';
  model = 'llama3.2';

  constructor(endpoint?: string, model?: string) {
    if (endpoint) this.endpoint = endpoint;
    if (model) this.model = model;
  }

  async isAvailable(): Promise<boolean> {
    try {
      const controller = new AbortController();
      const id = setTimeout(() => controller.abort(), 1200);
      const res = await fetch(`${this.endpoint}/api/tags`, { signal: controller.signal });
      clearTimeout(id);
      return res.ok;
    } catch {
      return false;
    }
  }

  async processTask(
    reportText: string,
    context?: { location?: string; title?: string },
    onTraceStep?: (step: AgentExecutionTraceStep) => void
  ): Promise<AgentOutput> {
    const isOnline = await this.isAvailable();
    if (!isOnline) {
      if (onTraceStep) {
        onTraceStep({
          step: 1,
          name: 'Ollama Connection Fallback',
          status: 'completed',
          detail: 'Local Ollama endpoint unreachable. Falling back seamlessly to Deterministic Rule Engine.',
          timestamp: new Date().toISOString()
        });
      }
      return deterministicAgent.processTask(reportText, context, onTraceStep);
    }

    const startTime = performance.now();
    try {
      if (onTraceStep) {
        onTraceStep({
          step: 1,
          name: 'Prompt Dispatch to Ollama',
          status: 'running',
          detail: `Sending inference query to ${this.endpoint} with model '${this.model}'...`,
          timestamp: new Date().toISOString()
        });
      }

      const systemPrompt = `You are FieldPilot, an offline-first rural task intelligence assistant.
Analyze the user field incident report and respond ONLY in valid JSON matching this schema:
{
  "category": "water_supply" | "agriculture" | "healthcare" | "infrastructure" | "education" | "other",
  "priority": "critical" | "high" | "medium" | "low",
  "confidence_score": number between 0.0 and 1.0,
  "summary": string,
  "location": string,
  "affected_population": number,
  "actions": [
    {
      "id": "act-1",
      "title": string,
      "description": string,
      "target_role": string,
      "urgency": "immediate" | "high" | "medium" | "routine",
      "completed": false
    }
  ],
  "reasoning": string[],
  "needs_human_verification": true,
  "verified_evidence": false
}`;

      const res = await fetch(`${this.endpoint}/api/generate`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          model: this.model,
          prompt: `${systemPrompt}\n\nField Incident Report:\n${reportText}`,
          stream: false,
          format: 'json'
        })
      });

      if (!res.ok) {
        throw new Error(`Ollama returned status ${res.status}`);
      }

      const data = await res.json();
      const parsed = JSON.parse(data.response);
      const endTime = performance.now();
      const processingTimeMs = Math.round(endTime - startTime);

      return {
        category: parsed.category || 'water_supply',
        priority: parsed.priority || 'medium',
        confidence_score: parsed.confidence_score || 0.9,
        summary: parsed.summary || reportText.slice(0, 100),
        location: parsed.location || context?.location || 'Field site',
        affected_population: parsed.affected_population || 0,
        actions: parsed.actions || [],
        reasoning: parsed.reasoning || ['Generated by local LLM model.'],
        needs_human_verification: true,
        verified_evidence: false,
        model_name: `Ollama (${this.model})`,
        processing_time_ms: processingTimeMs,
        resource_cost_mwh: Number((processingTimeMs * 0.005).toFixed(3))
      };
    } catch (err: any) {
      if (onTraceStep) {
        onTraceStep({
          step: 2,
          name: 'Ollama Parse Error Fallback',
          status: 'completed',
          detail: `Error communicating with local LLM (${err.message}). Using deterministic safety fallback.`,
          timestamp: new Date().toISOString()
        });
      }
      return deterministicAgent.processTask(reportText, context, onTraceStep);
    }
  }
}

export const ollamaAgent = new OllamaModelProvider();
